export function buildMetrics(
  projectId: string,
  updatedAt: string,
  opts: { exclude?: string[]; statusOverrides?: Record<string, MetricStatus> } = {},
): Metric[] {
  return METRIC_TEMPLATES.filter((t) => !opts.exclude?.includes(t.key)).map((t) => ({
    ...t,
    id: `m_${projectId}_${t.key}`,
    projectId,
    status: opts.statusOverrides?.[t.key] ?? "approved",
    updatedAt,
  }));
}
